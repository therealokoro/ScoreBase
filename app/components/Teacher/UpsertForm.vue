<script lang="ts" setup>
import { ICONS } from "~~/shared/constants/icons"
import { type UpsertTeacherInput } from "~~/shared/validators/actors"

const props = defineProps<{
  initialData?: UpsertTeacherInput & { id?: string }
  mode: "Edit" | "Create"
}>()

const emit = defineEmits<{ submit: [payload: UpsertTeacherInput] }>()
const isSheetOpen = defineModel<boolean>("open", { required: true })

const { data } = useListClasses()
const classes = computed(() => {
  return data.value?.map((curr) => ({ value: curr.id, label: curr.name })) || []
})

const isSubmitting = ref(false)
async function onSubmit(payload: UpsertTeacherInput) {
  isSubmitting.value = true
  try {
    emit("submit", payload)
  } finally {
    isSubmitting.value = false
  }
}

// Password reset (edit mode only): the admin confirms, then the teacher's password is set back
// to the default `pass-<surname>-123` generated by the server.
const resetPassword = useResetTeacherPassword()
const openResetDialog = ref(false)
const teacherId = computed(() => props.initialData?.id)

function handleResetPassword() {
  if (!teacherId.value) return
  useSonner.promise(resetPassword.mutateAsync({ id: teacherId.value }), {
    loading: "Resetting teacher's password, please wait...",
    success: (data: { success: boolean; password: string }) => {
      openResetDialog.value = false
      return `Password reset. New password: ${data.password}`
    },
    error: (err: any) => err.message
  })
}

// Never leave the confirmation open after the sheet closes (or switches teacher).
watch(isSheetOpen, (open) => {
  if (!open) openResetDialog.value = false
})
</script>

<template>
  <UiSheet v-model:open="isSheetOpen">
    <UiSheetContent
      side="right"
      class="w-full sm:max-w-none md:w-100"
      :title="`${mode} Teacher`"
      :description="`${mode === 'Create' ? 'Create a new' : 'Update'} teacher's info`"
    >
      <template #content>
        <FormKit
          type="form"
          :actions="false"
          :value="initialData"
          id="teacher-form"
          @submit="onSubmit"
        >
          <fieldset :disabled="isSubmitting" class="px-4">
            <FormKitMessages class="mb-4" />

            <FormKit
              name="name"
              label="Full Name"
              placeholder="Enter the teacher's full name here"
              help="e.g John Emeka Olabisi"
              validation="required"
            />

            <FormKit
              type="email"
              name="email"
              label="Email Address"
              placeholder="Enter the teacher's email address here"
              help="e.g john@gmail.com"
              validation="required|email"
            />

            <FormKit
              type="number"
              name="phoneNumber"
              label="Phone Number"
              placeholder="Enter the teacher's phone number here"
              help="e.g 09012345678"
              validation="required|number|exactLength:11"
            />

            <FormKit
              type="_select"
              name="classId"
              label="Class"
              :options="classes"
              placeholder="Pick a class to assign the teacher to"
              help="This is optional and can be done later"
            />
          </fieldset>
        </FormKit>

        <!-- Password reset: edit mode only, admin confirms before the reset -->
        <div v-if="mode === 'Edit' && teacherId" class="px-4 pb-4">
          <div class="space-y-2">
            <p class="text-sm font-medium">Password</p>
            <p class="text-xs text-muted-foreground">
              Reset this teacher's password back to the default so they can sign in again.
            </p>
            <UiButton
              type="button"
              variant="outline"
              size="sm"
              :icon="ICONS.password"
              :disabled="isSubmitting"
              @click="openResetDialog = true"
            >
              Reset Password
            </UiButton>
          </div>
        </div>

        <UiAlertDialog v-model:open="openResetDialog">
          <UiAlertDialogContent>
            <UiAlertDialogHeader>
              <UiAlertDialogTitle>Reset Teacher's Password</UiAlertDialogTitle>
              <UiAlertDialogDescription>
                This will reset {{ initialData?.name }}'s password to the default pattern
                <span class="font-medium">pass-&lt;surname&gt;-123</span>. Share the new password
                with the teacher so they can sign in and change it.
              </UiAlertDialogDescription>
            </UiAlertDialogHeader>
            <UiAlertDialogFooter>
              <UiAlertDialogCancel :disabled="resetPassword.isPending.value">
                Cancel
              </UiAlertDialogCancel>
              <UiAlertDialogAction
                :disabled="resetPassword.isPending.value"
                @click="handleResetPassword"
              >
                {{ resetPassword.isPending.value ? "Resetting..." : "Reset Password" }}
              </UiAlertDialogAction>
            </UiAlertDialogFooter>
          </UiAlertDialogContent>
        </UiAlertDialog>
      </template>

      <template #footer>
        <UiSheetFooter>
          <div class="w-full flex gap-1">
            <UiSheetClose as-child>
              <UiButton class="flex-1" variant="outline" type="button" :disabled="isSubmitting">
                Cancel
              </UiButton>
            </UiSheetClose>
            <UiButton
              class="flex-1"
              type="submit"
              form="teacher-form"
              :disabled="isSubmitting"
              :loading="isSubmitting"
            >
              {{ isSubmitting ? "Submitting..." : "Submit" }}
            </UiButton>
          </div>
        </UiSheetFooter>
      </template>
    </UiSheetContent>
  </UiSheet>
</template>
